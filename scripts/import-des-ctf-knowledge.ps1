param(
    [string]$DataRoot = "C:\RAG-Agent-Data",
    [string]$SourceRoot = "",
    [ValidatePattern('^[A-Za-z0-9._/-]+$')]
    [string]$Ref = "main",
    [switch]$Refresh,
    [string]$ServerRoot = $env:CHATCHAT_SERVER_ROOT
)

$ErrorActionPreference = "Stop"

$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$python = Join-Path $repoRoot ".venv\Scripts\python.exe"
$importer = Join-Path $repoRoot "scripts\import_des_ctf_knowledge.py"
$initScript = Join-Path $repoRoot "scripts\init-cybersec-kb.ps1"
$rebuildScript = Join-Path $repoRoot "scripts\rebuild-cybersec.ps1"

if ([string]::IsNullOrWhiteSpace($SourceRoot)) {
    $SourceRoot = Join-Path $DataRoot "sources\Des-CTF-Knowledge"
}
$SourceRoot = [System.IO.Path]::GetFullPath($SourceRoot)
$DataRoot = [System.IO.Path]::GetFullPath($DataRoot)
$destinationRoot = Join-Path $DataRoot "data\knowledge_base\cybersec\content\08_ctf_des_knowledge"
$metadataRoot = Join-Path $DataRoot "data\knowledge_base\cybersec\imports\Des-CTF-Knowledge"

foreach ($requiredPath in @($python, $importer, $initScript, $rebuildScript)) {
    if (-not (Test-Path -LiteralPath $requiredPath -PathType Leaf)) {
        throw "Required file was not found: $requiredPath. Create the repository virtualenv and install requirements.txt."
    }
}

function Invoke-Git {
    param([string[]]$Arguments)
    & git @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "Git command failed (exit code $LASTEXITCODE): git $($Arguments -join ' ')"
    }
}

$sourceParent = Split-Path -Parent $SourceRoot
New-Item -ItemType Directory -Force -Path $sourceParent | Out-Null
New-Item -ItemType Directory -Force -Path $DataRoot | Out-Null

if (-not (Test-Path -LiteralPath $SourceRoot -PathType Container)) {
    Write-Host "Cloning $Ref from Des-CTF-Knowledge..."
    Invoke-Git @("clone", "--depth", "1", "--branch", $Ref,
        "https://github.com/Dest1ny-Sec/Des-CTF-Knowledge.git", $SourceRoot)
} elseif (-not (Test-Path -LiteralPath (Join-Path $SourceRoot ".git") -PathType Container)) {
    throw "Source root exists but is not a Git checkout: $SourceRoot"
} elseif ($Refresh) {
    $status = (& git -C $SourceRoot status --porcelain)
    if ($LASTEXITCODE -ne 0) {
        throw "Unable to inspect source checkout status: $SourceRoot"
    }
    if ($status) {
        throw "Source checkout has local changes; refusing to reset it. Review or clean: $SourceRoot"
    }
    Write-Host "Refreshing source checkout from $Ref..."
    Invoke-Git @("-C", $SourceRoot, "fetch", "--depth", "1", "origin", $Ref)
    Invoke-Git @("-C", $SourceRoot, "reset", "--hard", "FETCH_HEAD")
} else {
    Write-Host "Using existing source checkout (use -Refresh to fetch $Ref)."
}

$commit = (& git -C $SourceRoot rev-parse HEAD).Trim()
if ($LASTEXITCODE -ne 0 -or [string]::IsNullOrWhiteSpace($commit)) {
    throw "Unable to read source commit: $SourceRoot"
}

# Keep local Ollama traffic off the workstation's HTTP proxy. GitHub access
# above may still use the configured proxy, but embedding/chat requests to
# 127.0.0.1 must remain direct.
$noProxyHosts = @(
    $env:NO_PROXY,
    $env:no_proxy,
    "127.0.0.1",
    "localhost"
) | Where-Object { -not [string]::IsNullOrWhiteSpace($_) }
$env:NO_PROXY = (($noProxyHosts -join ',').Split(',') |
    Where-Object { -not [string]::IsNullOrWhiteSpace($_) } |
    Select-Object -Unique) -join ','
$env:no_proxy = $env:NO_PROXY

# Initialize only the curated template files. Existing runtime files, including
# user-authored notes, are preserved by default.
& $initScript -DataRoot $DataRoot
if ($LASTEXITCODE -ne 0) {
    throw "Cybersecurity knowledge base initialization failed"
}

New-Item -ItemType Directory -Force -Path $destinationRoot | Out-Null
New-Item -ItemType Directory -Force -Path $metadataRoot | Out-Null

# Migrate artifacts created by older importer versions out of the indexed
# content directory. These names are generated by this importer only.
foreach ($artifactName in @(
    "import-manifest.json",
    "SOURCE-ATTRIBUTION.md",
    "UPSTREAM-LICENSE",
    "UPSTREAM-LICENSE.notice"
)) {
    $legacyArtifact = Join-Path $destinationRoot $artifactName
    if (Test-Path -LiteralPath $legacyArtifact -PathType Leaf) {
        Move-Item -LiteralPath $legacyArtifact -Destination (Join-Path $metadataRoot $artifactName) -Force
    }
}

Write-Host "Importing Markdown from commit $commit..."
$importArgs = @(
    $importer, "import",
    "--source-root", $SourceRoot,
    "--destination-root", $destinationRoot,
    "--metadata-root", $metadataRoot,
    "--commit", $commit
)
& $python @importArgs
if ($LASTEXITCODE -ne 0) {
    throw "Des-CTF-Knowledge import failed"
}
Write-Host "Rebuilding cybersec vector index..."
& $rebuildScript -DataRoot $DataRoot -ServerRoot $ServerRoot
if ($LASTEXITCODE -ne 0) {
    throw "Cybersecurity KB rebuild failed"
}

Write-Host "Des-CTF-Knowledge import completed: $destinationRoot"
